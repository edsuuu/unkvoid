        <h1>Política de privacidade</h1>
        <p class="lp-date">Última atualização: 11 de setembro de 2026</p>

        <p>O Unkvoid é um aplicativo para compartilhar a tela com pessoas que você escolhe. Esta política explica o que coletamos, por quê, e o que não coletamos. Ela foi escrita para ser lida, não para ser assinada sem ler.</p>

        <h2>O que coletamos</h2>

        <h3>Conta</h3>
        <p>A entrada é feita com a sua conta Google. Guardamos o nome, o e-mail e a foto de perfil que o Google nos devolve, mais um identificador da conta. Não temos acesso à sua senha nem a outros dados do Google.</p>

        <h3>Salas</h3>
        <p>Guardamos as salas que você cria, quem é o dono, e quem foi removido de cada uma. Isso é o que permite que uma sala continue sua depois que você fecha o app, e que uma pessoa removida não volte.</p>

        <h3>Diagnóstico</h3>
        <p>O app guarda um registro técnico do que aconteceu na sessão: versão, sistema operacional, eventos de conexão, contadores de transmissão. Ele não contém o conteúdo da sua tela nem do seu áudio.</p>
        <p><strong>Quando esse registro tem erro, o trecho dele é enviado para a gente na próxima vez que o app abre</strong>, junto com a versão e o sistema operacional. É o que nos deixa consertar falhas que só acontecem em algumas máquinas e que ninguém consegue descrever depois. O nome de usuário do seu computador é trocado por <span class="lp-mono">&lt;usuario&gt;</span> antes de sair. Sessão sem erro não envia nada.</p>

        <h3>Servidor</h3>
        <p>Como qualquer servidor na internet, o nosso registra o endereço IP e o horário de cada conexão. Usamos isso para limitar tentativas abusivas de entrar em salas e para investigar falhas.</p>

        <h2>O que não coletamos</h2>
        <p>A imagem e o áudio da sua tela passam pelo servidor cifrados e são retransmitidos na hora para quem está na sala. Nada disso é gravado, armazenado ou analisado. Não há rastreadores de publicidade, não vendemos dados e não usamos serviços de análise de comportamento.</p>

        <h2>Onde os dados ficam</h2>
        <p>Em um servidor nosso, hospedado em um provedor de nuvem. O tráfego de mídia atravessa esse servidor sem ser gravado. Os dados de conta e de salas ficam em um banco de dados nesse mesmo servidor.</p>

        <h2>Por quanto tempo</h2>
        <ul>
            <li>Conta e salas: enquanto a conta existir.</li>
            <li>Relatórios de diagnóstico: até 90 dias.</li>
            <li>Registros de conexão do servidor: até 30 dias.</li>
        </ul>

        <h2>Seus direitos</h2>
        <p>Você pode pedir uma cópia do que guardamos sobre você, corrigir o que estiver errado, ou apagar a conta e tudo o que está ligado a ela. Basta escrever para <a href="mailto:contato@unkvoid.com">contato@unkvoid.com</a> pelo mesmo e-mail da conta. Apagar a conta apaga as salas que você criou.</p>

        <h2>Cookies</h2>
        <p>O site usa apenas o cookie de sessão necessário para manter você conectado. Não há cookies de terceiros.</p>

        <h2>Mudanças</h2>
        <p>Se esta política mudar, a data no topo muda junto. Mudanças que afetem o que coletamos serão avisadas dentro do app.</p>
